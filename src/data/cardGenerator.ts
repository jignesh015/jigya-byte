import type { ContentCard, Topic } from './cardContent';

export type GeneratorSettings = { enabled: boolean; serviceUrl: string };
export const defaultGeneratorSettings: GeneratorSettings = { enabled: false, serviceUrl: 'http://127.0.0.1:4318' };

export interface CardGenerator {
  generate(topic: Topic): Promise<ContentCard>;
}

export function validateServiceUrl(value: string): string {
  const url = new URL(value.trim());
  const privateHost = url.hostname === 'localhost' || url.hostname === '127.0.0.1'
    || /^10\.\d+\.\d+\.\d+$/.test(url.hostname) || /^192\.168\.\d+\.\d+$/.test(url.hostname)
    || /^172\.(1[6-9]|2\d|3[01])\.\d+\.\d+$/.test(url.hostname);
  if (!privateHost || !['http:', 'https:'].includes(url.protocol) || url.username || url.password
      || url.pathname !== '/' || url.search || url.hash) {
    throw new Error('Use a local PC address, such as http://192.168.1.10:4318.');
  }
  return url.origin;
}

export class LocalCardGenerator implements CardGenerator {
  constructor(private readonly serviceUrl: string) {}

  async generate(topic: Topic): Promise<ContentCard> {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 90000);
    try {
      const response = await fetch(`${validateServiceUrl(this.serviceUrl)}/generate`, {
        method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ topicId: topic.id }), signal: controller.signal,
      });
      if (!response.ok) throw new Error('The local model is unavailable. Use public discovery or read your saved cards.');
      const card = await response.json() as ContentCard;
      if (card.providerId !== 'local-ai' || typeof card.id !== 'string' || !card.id.startsWith('local-ai-')
          || typeof card.title !== 'string' || !card.title.trim() || card.title.length > 100
          || typeof card.summary !== 'string' || !card.summary.trim() || card.summary.length > 240
          || typeof card.explanation !== 'string' || !card.explanation.trim() || card.explanation.length > 4000
          || card.primaryTopicId !== topic.id) throw new Error('The local model returned an unusable card. Your library is unchanged.');
      // Metadata is controlled here, not trusted from generated output.
      return { ...card, topicIds: [topic.id], sourceName: 'AI generated · local model', sourceUrl: null,
        attribution: 'Generated by a local model on your PC. Unverified explanation; check claims independently.',
        license: 'Generated text; model terms apply', licenseUrl: null, retrievedAt: new Date().toISOString() };
    } catch (error) {
      if (error instanceof Error && error.message.startsWith('The local')) throw error;
      throw new Error('Could not reach the local PC service. Use public discovery or read your saved cards.');
    } finally { clearTimeout(timeout); }
  }
}
